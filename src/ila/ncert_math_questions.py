def _make_q(
    qid: str,
    kind: str,
    prompt: str,
    answer: str,
    chapter_num: int,
    chapter_title: str,
    difficulty: int,
    explanation: str,
    options: tuple[str, ...] = (),
    keywords: tuple[str, ...] = (),
) -> QuizQuestion:
    from ila.quiz import QuizQuestion

    ans_idx = options.index(answer) if (options and answer in options) else None
    return QuizQuestion(
        id=qid,
        kind=kind,  # type: ignore[arg-type]
        prompt=prompt,
        answer=answer,
        topic=chapter_title,
        difficulty=difficulty,
        explanation=explanation,
        source="ncert_exercise",
        chapter_number=chapter_num,
        chapter_title=chapter_title,
        options=options,
        answer_index=ans_idx,
        keywords=keywords,
    )


